use crate::error::Result;
use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};

/// A single command extracted from a terminal recording.
#[derive(Debug, Clone)]
pub struct ExtractedCommand {
    /// The command string as typed by the user
    pub command: String,
    /// Timestamp (seconds from start) when the command was entered
    pub timestamp: f64,
    /// Sequential index of the command (1-based)
    pub index: usize,
}

/// Result of command extraction from a .cast file.
#[derive(Debug, Clone)]
pub struct CommandLog {
    /// All extracted commands in order
    pub commands: Vec<ExtractedCommand>,
    /// Path the log was saved to (if saved)
    pub saved_path: Option<PathBuf>,
    /// Recording title from the cast header (if present)
    pub title: Option<String>,
    /// Recording shell from the cast header (if present)
    pub shell: Option<String>,
    /// Total recording duration in seconds
    pub duration_secs: f64,
}

impl CommandLog {
    /// Format the command log as a human-readable report.
    pub fn to_report(&self) -> String {
        let mut report = String::new();

        report.push_str("# Terminal Session Command Log\n");
        report.push_str(&format!("# Generated by cast2video\n"));

        if let Some(ref title) = self.title {
            report.push_str(&format!("# Title: {}\n", title));
        }
        if let Some(ref shell) = self.shell {
            report.push_str(&format!("# Shell: {}\n", shell));
        }
        report.push_str(&format!(
            "# Duration: {:.1}s | Commands: {}\n",
            self.duration_secs,
            self.commands.len()
        ));
        report.push_str("#\n");
        report.push_str(&format!(
            "# {:<5} {:<10} {}\n",
            "No.", "Time", "Command"
        ));
        report.push_str(&format!("# {}\n", "-".repeat(60)));

        for cmd in &self.commands {
            let time_str = format!("{:.1}s", cmd.timestamp);
            report.push_str(&format!(
                "  {:<5} {:<10} {}\n",
                cmd.index, time_str, cmd.command
            ));
        }

        report.push_str(&format!("\n# Total: {} commands\n", self.commands.len()));
        report
    }

    /// Format the command log as a plain executable shell script.
    pub fn to_script(&self) -> String {
        let mut script = String::new();

        script.push_str("#!/usr/bin/env bash\n");
        script.push_str("# Terminal Session Commands - Extracted by cast2video\n");

        if let Some(ref title) = self.title {
            script.push_str(&format!("# Title: {}\n", title));
        }
        script.push_str(&format!("# Total Commands: {}\n\n", self.commands.len()));

        for cmd in &self.commands {
            script.push_str(&format!("{}\n", cmd.command));
        }

        script
    }

    /// Save the command log to a file (report format).
    pub fn save_report<P: AsRef<Path>>(&self, path: P) -> Result<PathBuf> {
        let path = path.as_ref().to_path_buf();
        fs::write(&path, self.to_report())?;
        Ok(path)
    }

    /// Save the commands as an executable shell script.
    pub fn save_script<P: AsRef<Path>>(&self, path: P) -> Result<PathBuf> {
        let path = path.as_ref().to_path_buf();
        fs::write(&path, self.to_script())?;

        // Make executable on Unix
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let perms = fs::Permissions::from_mode(0o755);
            let _ = fs::set_permissions(&path, perms);
        }

        Ok(path)
    }
}

/// Extract commands from a .cast file by parsing input ("i") events.
///
/// When `--stdin` was used during recording, input keystrokes are stored
/// as `[timestamp, "i", "keystroke_data"]` events. We reconstruct full
/// commands by accumulating characters until a newline (Enter key) is detected.
///
/// If no input events exist, falls back to heuristic output parsing.
pub fn extract_commands<P: AsRef<Path>>(cast_path: P) -> Result<CommandLog> {
    let content = fs::read_to_string(cast_path.as_ref())?;
    let mut lines = content.lines();

    // Parse header (first line)
    let header_line = lines.next().unwrap_or("{}");
    let header: Value = serde_json::from_str(header_line).unwrap_or(Value::Null);

    let title = header
        .get("title")
        .and_then(|v| v.as_str())
        .map(|s| s.to_string());
    let shell = header
        .get("env")
        .and_then(|e| e.get("SHELL"))
        .and_then(|v| v.as_str())
        .map(|s| s.to_string());

    // Collect all events
    let mut input_events: Vec<(f64, String)> = Vec::new();
    let mut output_events: Vec<(f64, String)> = Vec::new();
    let mut max_timestamp: f64 = 0.0;

    for line in lines {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }

        let event: Value = match serde_json::from_str(line) {
            Ok(v) => v,
            Err(_) => continue,
        };

        let arr = match event.as_array() {
            Some(a) if a.len() >= 3 => a,
            _ => continue,
        };

        let ts = arr[0].as_f64().unwrap_or(0.0);
        let event_type = arr[1].as_str().unwrap_or("");
        let data = arr[2].as_str().unwrap_or("").to_string();

        if ts > max_timestamp {
            max_timestamp = ts;
        }

        match event_type {
            "i" => input_events.push((ts, data)),
            "o" => output_events.push((ts, data)),
            _ => {}
        }
    }

    // Try stdin-based extraction first (most reliable)
    let commands = if !input_events.is_empty() {
        extract_from_input_events(&input_events)
    } else {
        // Fallback: heuristic extraction from output events
        extract_from_output_events(&output_events)
    };

    Ok(CommandLog {
        commands,
        saved_path: None,
        title,
        shell,
        duration_secs: max_timestamp,
    })
}

/// Reconstruct commands from input ("i") events.
///
/// Input events contain raw keystrokes. We accumulate characters into a
/// buffer and flush as a command when we see `\r` or `\n` (Enter key).
/// Backspace (`\x7f`, `\x08`) removes the last character.
/// Ctrl+C (`\x03`) discards the current buffer.
fn extract_from_input_events(events: &[(f64, String)]) -> Vec<ExtractedCommand> {
    let mut commands = Vec::new();
    let mut buffer = String::new();
    let mut cmd_start_ts: f64 = 0.0;
    let mut index = 0;

    for (ts, data) in events {
        for ch in data.chars() {
            match ch {
                '\r' | '\n' => {
                    let trimmed = buffer.trim().to_string();
                    if !trimmed.is_empty() {
                        index += 1;
                        commands.push(ExtractedCommand {
                            command: trimmed,
                            timestamp: cmd_start_ts,
                            index,
                        });
                    }
                    buffer.clear();
                    cmd_start_ts = *ts;
                }
                '\x7f' | '\x08' => {
                    // Backspace
                    buffer.pop();
                }
                '\x03' => {
                    // Ctrl+C — discard current input
                    buffer.clear();
                    cmd_start_ts = *ts;
                }
                '\x04' => {
                    // Ctrl+D (EOF) — ignore
                }
                '\x1b' => {
                    // Start of escape sequence — skip (arrows, etc.)
                    // We'll handle multi-char escapes by ignoring non-printable
                }
                '\t' => {
                    // Tab completion — keep going, shell will expand in output
                }
                c if c.is_control() => {
                    // Skip other control characters
                }
                c => {
                    if buffer.is_empty() {
                        cmd_start_ts = *ts;
                    }
                    buffer.push(c);
                }
            }
        }
    }

    // Flush any remaining buffer
    let trimmed = buffer.trim().to_string();
    if !trimmed.is_empty() {
        index += 1;
        commands.push(ExtractedCommand {
            command: trimmed,
            timestamp: cmd_start_ts,
            index,
        });
    }

    commands
}

/// Heuristic extraction from output ("o") events.
///
/// When stdin capture is unavailable, we look for common shell prompt patterns
/// in the output stream and extract the text that follows as commands.
/// This is less reliable but provides a best-effort extraction.
fn extract_from_output_events(events: &[(f64, String)]) -> Vec<ExtractedCommand> {
    let mut commands = Vec::new();
    let mut index = 0;

    // Concatenate all output into a single stream with timestamps
    let mut full_output = String::new();
    let mut char_timestamps: Vec<f64> = Vec::new();

    for (ts, data) in events {
        for _ in data.chars() {
            char_timestamps.push(*ts);
        }
        full_output.push_str(data);
    }

    // Strip ANSI escape sequences for cleaner parsing
    let stripped = strip_ansi_codes(&full_output);

    // Look for prompt patterns: `$ `, `# `, `> `, or `username@host:path$ `
    // and extract the text between the prompt and the next newline
    for line in stripped.lines() {
        let trimmed = line.trim();

        // Common prompt endings
        let cmd_text = if let Some(pos) = trimmed.rfind("$ ") {
            Some(trimmed[pos + 2..].trim())
        } else if let Some(pos) = trimmed.rfind("# ") {
            Some(trimmed[pos + 2..].trim())
        } else if let Some(pos) = trimmed.rfind("> ") {
            // Be careful not to match output redirection
            let before = &trimmed[..pos];
            if before.contains('@') || before.contains(':') || before.is_empty() {
                Some(trimmed[pos + 2..].trim())
            } else {
                None
            }
        } else {
            None
        };

        if let Some(cmd) = cmd_text {
            if !cmd.is_empty()
                && !cmd.starts_with('[')
                && cmd.len() < 500
            {
                index += 1;
                commands.push(ExtractedCommand {
                    command: cmd.to_string(),
                    timestamp: 0.0, // imprecise in output mode
                    index,
                });
            }
        }
    }

    commands
}

/// Strip ANSI escape sequences from a string.
fn strip_ansi_codes(s: &str) -> String {
    let mut result = String::with_capacity(s.len());
    let mut chars = s.chars().peekable();

    while let Some(ch) = chars.next() {
        if ch == '\x1b' {
            // Consume escape sequence
            if chars.peek() == Some(&'[') {
                chars.next(); // consume '['
                // Read until we find a letter (the terminator)
                while let Some(&c) = chars.peek() {
                    chars.next();
                    if c.is_ascii_alphabetic() || c == '~' {
                        break;
                    }
                }
            } else if chars.peek() == Some(&']') {
                chars.next(); // consume ']'
                // OSC sequence — terminated by BEL (\x07) or ST (\x1b\\)
                while let Some(&c) = chars.peek() {
                    chars.next();
                    if c == '\x07' {
                        break;
                    }
                    if c == '\x1b' {
                        if chars.peek() == Some(&'\\') {
                            chars.next();
                        }
                        break;
                    }
                }
            }
        } else {
            result.push(ch);
        }
    }

    result
}
